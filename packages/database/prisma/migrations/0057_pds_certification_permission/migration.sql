FROM "roles" r
JOIN "permissions" p ON p."code" = 'personnel.pds.certify'
WHERE r."code" IN ('personnel_records_officer', 'hrmo_administrator')
  AND r."agency_id" IS NULL
ON CONFLICT DO NOTHING;

